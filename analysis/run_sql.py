"""
SQL verification harness.

Loads the cleaned star schema (powerbi/data/*.csv, generated by
powerbi/prepare_data.py) into an in-memory SQLite database, executes the
validation queries in sql/retention_validation.sql EXACTLY as written in
that file, and writes the results to src/data/sqlResults.json.

Run from the project root:
    python analysis/run_sql.py

The queries in sql/retention_validation.sql are the single source of
truth: this harness strips comment lines, splits on blank-line+semicolon
delimiters and executes each statement verbatim, so the SQL shown in the
dashboard is the SQL that actually ran.
"""
import json
import re
import sqlite3
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "powerbi", "data")
SQLFILE = os.path.join(ROOT, "sql", "retention_validation.sql")
OUT = os.path.join(ROOT, "src", "data", "sqlResults.json")

QUERIES = [
    ("Q1", "Dataset scale"),
    ("Q2", "Revenue reconciliation"),
    ("Q3", "Repeat purchase rate (two methods)"),
    ("Q4", "Top-20% revenue concentration"),
    ("Q5", "RFM segment distribution"),
    ("Q6", "Inactivity bands"),
    ("Q7", "Monthly non-return series"),
]


def load_db():
    import pandas as pd

    con = sqlite3.connect(":memory:")
    fact = pd.read_csv(os.path.join(DATA, "fact_sales.csv"))
    fact["InvoiceDate"] = pd.to_datetime(fact["InvoiceDate"]).dt.strftime("%Y-%m-%d %H:%M:%S")
    fact.to_sql("fact_sales", con, index=False)
    pd.read_csv(os.path.join(DATA, "dim_customer.csv")).to_sql("dim_customer", con, index=False)
    return con


def parse_statements(sql_text):
    # strip full-line comments, keep inline structure, split on ';'
    lines = [ln for ln in sql_text.splitlines() if not ln.strip().startswith("--")]
    text = "\n".join(lines)
    stmts = [s.strip() for s in text.split(";") if s.strip()]
    return stmts


def main():
    con = load_db()
    sql_text = open(SQLFILE, encoding="utf-8").read()
    stmts = parse_statements(sql_text)
    assert len(stmts) == len(QUERIES), f"expected {len(QUERIES)} statements, parser found {len(stmts)}"

    results = []
    checks = []
    for (qid, title), sql in zip(QUERIES, stmts):
        cur = con.execute(sql)
        cols = [d[0] for d in cur.description]
        rows = [list(r) for r in cur.fetchall()]
        results.append({
            "id": qid,
            "title": title,
            "sql": sql.strip(),
            "columns": cols,
            "rows": rows,
        })
        print(f"{qid} {title}: ", rows[:2], f"({len(rows)} rows)" if len(rows) > 2 else "")

    # automated pass/fail checks against the Python pipeline's values
    r = {res["id"]: res for res in results}
    def scalar(qid, col, row=0):
        res = r[qid]
        return res["rows"][row][res["columns"].index(col)]

    checks.append({"check": "Rows analysed match 397,884", "expected": 397884, "sql": scalar("Q1", "rows_analysed"), "pass": scalar("Q1", "rows_analysed") == 397884})
    checks.append({"check": "Customers match 4,338", "expected": 4338, "sql": scalar("Q1", "customers"), "pass": scalar("Q1", "customers") == 4338})
    checks.append({"check": "Invoices match 18,532", "expected": 18532, "sql": scalar("Q1", "invoices"), "pass": scalar("Q1", "invoices") == 18532})
    checks.append({"check": "Occasions match 18,440", "expected": 18440, "sql": scalar("Q1", "purchase_occasions"), "pass": scalar("Q1", "purchase_occasions") == 18440})
    checks.append({"check": "Revenue matches GBP 8,911,407.90", "expected": 8911407.90, "sql": scalar("Q2", "revenue_column"), "pass": abs(scalar("Q2", "revenue_column") - 8911407.90) < 0.05})
    checks.append({"check": "Qty x price == revenue column", "expected": 8911407.90, "sql": scalar("Q2", "revenue_qty_x_price"), "pass": abs(scalar("Q2", "revenue_qty_x_price") - 8911407.90) < 0.05})
    checks.append({"check": "Invoice repeat rate matches 65.6", "expected": 65.6, "sql": scalar("Q3", "repeat_rate_invoices_pct"), "pass": abs(scalar("Q3", "repeat_rate_invoices_pct") - 65.6) < 0.05})
    checks.append({"check": "Occasion repeat rate matches 65.5", "expected": 65.5, "sql": scalar("Q3", "repeat_rate_occasions_pct"), "pass": abs(scalar("Q3", "repeat_rate_occasions_pct") - 65.5) < 0.05})
    checks.append({"check": "Top-20% customers = 867", "expected": 867, "sql": scalar("Q4", "top20_customers"), "pass": scalar("Q4", "top20_customers") == 867})
    checks.append({"check": "Top-20% share = 74.6%", "expected": 74.6, "sql": scalar("Q4", "top20_share_pct"), "pass": abs(scalar("Q4", "top20_share_pct") - 74.6) < 0.05})
    checks.append({"check": "Inactive 90d = 1,441", "expected": 1441, "sql": scalar("Q6", "inactive_90d"), "pass": scalar("Q6", "inactive_90d") == 1441})
    checks.append({"check": "Inactive 180d = 858", "expected": 858, "sql": scalar("Q6", "inactive_180d"), "pass": scalar("Q6", "inactive_180d") == 858})

    series = {row[0]: row[2] for row in r["Q7"]["rows"]}
    # MonthKey mapping: Dec2010=24132 .. Oct2011=24142 (Nov 24143 excluded, partial Dec follow-up)
    checks.append({"check": "Dec non-return = 63.4%", "expected": 63.4, "sql": series.get(24132), "pass": abs(series.get(24132, 0) - 63.4) < 0.05})
    checks.append({"check": "Mar non-return = 68.8% (peak)", "expected": 68.8, "sql": series.get(24135), "pass": abs(series.get(24135, 0) - 68.8) < 0.05})
    checks.append({"check": "Oct non-return = 54.4%", "expected": 54.4, "sql": series.get(24142), "pass": abs(series.get(24142, 0) - 54.4) < 0.05})

    seg = {row[0]: row[1] for row in r["Q5"]["rows"]}
    checks.append({"check": "Champions = 980", "expected": 980, "sql": seg.get("Champions"), "pass": seg.get("Champions") == 980})
    checks.append({"check": "Lost = 1,535", "expected": 1535, "sql": seg.get("Lost"), "pass": seg.get("Lost") == 1535})

    out = {
        "engine": "SQLite (in-memory), loaded from powerbi/data/*.csv prepared by powerbi/prepare_data.py",
        "sourceFile": "sql/retention_validation.sql",
        "queries": results,
        "checks": checks,
        "allPassed": all(c["pass"] for c in checks),
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)

    passed = sum(c["pass"] for c in checks)
    print(f"\n{passed}/{len(checks)} checks passed -> {OUT}")
    if not out["allPassed"]:
        for c in checks:
            if not c["pass"]:
                print("FAILED:", c)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
